// Downloads the web fonts the site uses from Google Fonts (all under the SIL Open Font License), saves them as woff2
// files and writes the matching @font-face rules.
//
//   npm run build:fonts                  files -> public/assets/fonts, rules -> public/assets/css/parts/00-fonts.css
//   node scripts/get-fonts.mjs <dir>     the same, into <dir>/fonts and <dir>/00-fonts.css (to look before replacing)
//
// Only needed when the fonts change; the results are committed. Needs network access. Run `npm run format` afterwards,
// because the rules are written on one line each.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = process.argv[2] ? path.resolve(process.argv[2]) : null;
const FONT_DIR = outDir ? path.join(outDir, 'fonts') : path.join(ROOT, 'public', 'assets', 'fonts');
const CSS_FILE = outDir
  ? path.join(outDir, '00-fonts.css')
  : path.join(ROOT, 'public', 'assets', 'css', 'parts', '00-fonts.css');

// Google serves different font files (woff2, split into unicode subsets) depending on the browser, so ask as a current one.
const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

const FONTS = [
  {
    key: 'young-serif',
    url: 'https://fonts.googleapis.com/css2?family=Young+Serif&display=swap',
    subsets: ['latin', 'latin-ext'],
  },
  {
    key: 'dm-sans',
    url: 'https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,100..1000&display=swap',
    subsets: ['latin', 'latin-ext'],
  },
  // Two tiny subsets that only carry the Bangladeshi Taka sign (U+09F3), so prices look the same in every font stack.
  {
    key: 'taka-sans',
    family: 'Taka Sans',
    url: 'https://fonts.googleapis.com/css2?family=Noto+Sans+Bengali:wght@500;700&text=%E0%A7%B3',
    subsets: ['*'],
  },
  {
    key: 'taka-serif',
    family: 'Taka Serif',
    url: 'https://fonts.googleapis.com/css2?family=Noto+Serif+Bengali:wght@500&text=%E0%A7%B3',
    subsets: ['*'],
  },
];

async function fetchOk(url) {
  const res = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
  if (!res.ok) throw new Error(`${url} answered ${res.status}`);
  return res;
}

/** The @font-face blocks of a Google Fonts stylesheet, each with the name of the subset it covers. */
function parseFontFaces(css) {
  return [...css.matchAll(/(?:\/\*\s*([\w-]+)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g)].map((m) => ({
    subset: m[1] || '*', // requests for specific text (the Taka sign) come back as one unlabelled block
    body: m[2],
  }));
}

await fs.mkdir(FONT_DIR, { recursive: true });
let rules =
  '/* Self-hosted fonts (SIL Open Font License). Generated by scripts/get-fonts.mjs; run `npm run format` after it */\n';

for (const font of FONTS) {
  const blocks = parseFontFaces(await (await fetchOk(font.url)).text());
  let saved = 0;
  for (const { subset, body } of blocks) {
    if (!font.subsets.includes('*') && !font.subsets.includes(subset)) continue;
    const src = body.match(/url\((https:[^)]+)\)/)[1];
    const family = font.family ?? body.match(/font-family:\s*'([^']+)'/)[1];
    const style = body.match(/font-style:\s*(\w+)/)?.[1] ?? 'normal';
    const weight = body.match(/font-weight:\s*([\d\s]+)/)[1].trim();
    const range = body.match(/unicode-range:\s*([^;]+);/)?.[1];
    const file = `${font.key}${font.subsets.includes('*') ? `-${weight.replace(/\s+/g, '-')}` : `-${subset}`}${style === 'italic' ? '-italic' : ''}.woff2`;

    await fs.writeFile(path.join(FONT_DIR, file), Buffer.from(await (await fetchOk(src)).arrayBuffer()));
    rules +=
      `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;` +
      `src:url(/assets/fonts/${file}) format('woff2');${range ? `unicode-range:${range};` : ''}}\n`;
    saved++;
    console.log('saved', file);
  }
  if (!saved) throw new Error(`no font files found for ${font.key}`);
}

await fs.writeFile(CSS_FILE, rules);
console.log(`wrote ${path.relative(ROOT, CSS_FILE)}`);
